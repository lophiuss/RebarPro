-- ============================================================
-- 3. TIGHTEN RLS ON EXISTING REBAR TABLES
--    Today any authenticated user (in this whole Supabase project) can read/
--    write every rebar table. Once cement accounts share this project that
--    would let cement-only staff see/edit rebar data. Replace the blanket
--    "authenticated" policies with department-membership checks.
-- ============================================================

do $$
declare
  tbl text;
begin
  foreach tbl in array array[
    'projects','project_types','rebar_sizes','transactions','stock_takes','targets'
  ] loop
    execute format('drop policy if exists "Authenticated users can read %s" on public.%I', tbl, tbl);
    execute format('drop policy if exists "Authenticated users can insert %s" on public.%I', tbl, tbl);
    execute format('drop policy if exists "Authenticated users can update %s" on public.%I', tbl, tbl);
    execute format('drop policy if exists "Authenticated users can delete %s" on public.%I', tbl, tbl);
    execute format('create policy "rebar members select" on public.%I for select using (public.has_dept_access(''rebar''))', tbl);
    execute format('create policy "rebar members insert" on public.%I for insert with check (public.has_dept_access(''rebar''))', tbl);
    execute format('create policy "rebar members update" on public.%I for update using (public.has_dept_access(''rebar''))', tbl);
    execute format('create policy "rebar members delete" on public.%I for delete using (public.has_dept_access(''rebar''))', tbl);
  end loop;
end $$;

-- global_settings: keep public read (it's just unit/coverage-day preferences),
