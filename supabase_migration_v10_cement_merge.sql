create table public.user_department_access (
  user_id uuid references public.profiles(id) on delete cascade not null,
  department text not null check (department in ('rebar','cement')),
  role text not null,
  granted_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  primary key (user_id, department)
);

create or replace function public.has_dept_access(dept text)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.user_department_access uda
    where uda.user_id = auth.uid() and uda.department = dept
  );
$$;

create or replace function public.is_dept_admin(dept text)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.user_department_access uda
    where uda.user_id = auth.uid() and uda.department = dept and uda.role = 'admin'
  );
$$;

grant execute on function public.has_dept_access(text) to authenticated;
grant execute on function public.is_dept_admin(text) to authenticated;

alter table public.user_department_access enable row level security;
create policy "self can view own access rows" on public.user_department_access for select using (user_id = auth.uid());
create policy "dept admins can view dept rows" on public.user_department_access for select using (public.is_dept_admin(department));
create policy "dept admins can grant dept rows" on public.user_department_access for insert with check (public.is_dept_admin(department));
create policy "dept admins can update dept rows" on public.user_department_access for update using (public.is_dept_admin(department));
create policy "dept admins can revoke dept rows" on public.user_department_access for delete using (public.is_dept_admin(department));

