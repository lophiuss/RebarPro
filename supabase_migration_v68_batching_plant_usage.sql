-- ============================================================
-- v68: Batching Plant Usage API Table
-- Stores actual usage and theoretical usage by material, date, and time
-- for ready-mix concrete batching plant operations.
-- Used by the external batching API for integration with third-party websites.
-- ============================================================

create table if not exists public.batching_plant_usage (
  id bigint generated by default as identity primary key,
  plant_id integer references public.cement_plants(id) on delete set null,
  plant_name text not null,
  material_id integer references public.cement_materials(id) on delete set null,
  material_name text not null,
  batched_at timestamptz not null default now(),
  actual_usage numeric not null,
  theoretical_usage numeric not null,
  variance numeric generated always as (actual_usage - theoretical_usage) stored,
  variance_pct numeric generated always as (
    case when theoretical_usage <> 0 then round(((actual_usage - theoretical_usage) / theoretical_usage) * 100, 2)
         else null
    end
  ) stored,
  unit text not null default 'kg',
  mix_code text,
  batch_ticket_no text,
  volume_m3 numeric,
  operator text,
  remarks text,
  metadata jsonb default '{}'::jsonb,
  created_at timestamptz not null default now()
);

-- Performance indexes for date/time range queries and filtering
create index if not exists idx_batching_usage_batched_at
  on public.batching_plant_usage (batched_at desc);

create index if not exists idx_batching_usage_mat_time
  on public.batching_plant_usage (material_name, batched_at desc);

create index if not exists idx_batching_usage_plant_time
  on public.batching_plant_usage (plant_name, batched_at desc);

create index if not exists idx_batching_usage_ticket
  on public.batching_plant_usage (batch_ticket_no);

-- Row Level Security
alter table public.batching_plant_usage enable row level security;

-- Authenticated internal users can view batching logs if they have cement access
create policy "cement_batching_usage_select"
  on public.batching_plant_usage for select
  to authenticated
  using (
    (select public.has_dept_access('cement'))
    or exists (select 1 from public.app_super_admins where user_id = auth.uid())
  );

-- Authenticated internal users can insert batching logs if they have cement access
create policy "cement_batching_usage_insert"
  on public.batching_plant_usage for insert
  to authenticated
  with check (
    (select public.has_dept_access('cement'))
    or exists (select 1 from public.app_super_admins where user_id = auth.uid())
  );

